import path from 'node:path';
import { APPLIED_MIGRATION_REASON, deny, isAppliedMigration, readInput, repoRoot, toPosix } from './lib.mjs';

const GENERATED = [
  ['frontend/src/app/core/api/', 'The frontend API client is generated by ng-openapi-gen from api/openapi.yaml.'],
  ['backend/target/', 'backend/target is build output; the API interfaces there are generated from api/openapi.yaml.'],
];

const input = readInput();
const filePath = input.tool_input?.file_path ?? input.tool_input?.notebook_path;
if (!filePath) process.exit(0);

const root = repoRoot(filePath);
if (!root) process.exit(0);
const rel = toPosix(path.relative(root, path.resolve(filePath)));
if (rel.startsWith('..')) process.exit(0);

for (const [prefix, why] of GENERATED) {
  if (rel.startsWith(prefix)) {
    deny(`${rel} is generated code. ${why} Change the contract in api/openapi.yaml and regenerate instead.`);
  }
}

if (isAppliedMigration(root, rel)) deny(`${rel}: ${APPLIED_MIGRATION_REASON}`);
