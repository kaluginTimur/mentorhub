import path from 'node:path';
import {
  DEFAULT_BRANCH_REASON,
  MIGRATION_IN_MAIN_REASON,
  allow,
  deny,
  isCommitted,
  isMigrationInMain,
  isThisProject,
  onDefaultBranch,
  readInput,
  resolveRepoRelative,
} from './lib.mjs';

const GENERATED = [
  ['frontend/src/app/core/api/', 'The frontend API client is generated by ng-openapi-gen from api/openapi.yaml.'],
  ['backend/target/', 'backend/target is build output; the API interfaces there are generated from api/openapi.yaml.'],
];

const input = readInput();
const toolName = input.toolCall?.name ?? '';
const filePath = input.toolCall?.args?.Path;
if (!filePath) allow();

if (toolName === 'read_file') {
  const base = path.basename(filePath);
  if (/^\.env(\..+)?$/.test(base)) {
    deny(`Blocked: reading ${base} is denied because .env files may contain secrets.`);
  }
  allow();
}

const resolved = resolveRepoRelative(filePath, input.cwd);
if (!resolved) allow();
const { root, rel } = resolved;

for (const [prefix, why] of GENERATED) {
  if (rel.startsWith(prefix)) {
    deny(`${rel} is generated code. ${why} Change the contract in api/openapi.yaml and regenerate instead.`);
  }
}

if (isMigrationInMain(root, rel)) deny(`${rel}: ${MIGRATION_IN_MAIN_REASON}`);

if (isThisProject(root, input.workspacePaths) && onDefaultBranch(root) && isCommitted(root, rel)) {
  deny(`${rel}: ${DEFAULT_BRANCH_REASON}`);
}

allow();
